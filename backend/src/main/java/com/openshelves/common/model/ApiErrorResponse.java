package com.openshelves.common.model;

import com.fasterxml.jackson.annotation.JsonAnyGetter;
import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonInclude.Include;
import com.fasterxml.jackson.annotation.JsonPropertyOrder;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.ToString;
import org.springframework.http.HttpStatus;

import java.net.URI;
import java.time.Instant;
import java.util.LinkedHashMap;
import java.util.Map;

/// Error response body following RFC 9457 (Problem Details for HTTP APIs),
/// serialized as `application/problem+json`.
///
/// Besides the standard members, it carries a `timestamp`, a machine-readable
/// `code` for clients to branch on, and any extra members added through
/// [#withProperty], which are written at the top level of the JSON object.
@Getter
@ToString
@JsonInclude(Include.NON_EMPTY)
@JsonPropertyOrder({"title", "status", "detail", "instance", "code", "timestamp"})
public class ApiErrorResponse {

    // -------------------------------------------------------------------------
    // Standard members (RFC 9457)
    // -------------------------------------------------------------------------

    /// Short, human-readable summary of the problem type; defaults to the HTTP reason phrase (RFC 9457 §3.1.3).
    private String title;

    /// HTTP status code generated by the server for this occurrence (RFC 9457 §3.1.2).
    private final int status;

    /// Human-readable explanation specific to this occurrence of the problem (RFC 9457 §3.1.4).
    private String detail;

    /// URI identifying this specific occurrence, typically the request path (RFC 9457 §3.1.5).
    private URI instance;


    // -------------------------------------------------------------------------
    // Extension members
    // -------------------------------------------------------------------------

    /// Stable, machine-readable error code; defaults to the HTTP status name (e.g. `UNAUTHORIZED`).
    private String code;

    /// Time the error response was created, in UTC; defaults to now.
    private Instant timestamp = Instant.now();

    /// Additional members, serialized at the top level of the response.
    @Getter(AccessLevel.NONE)
    private final Map<String, Object> properties = new LinkedHashMap<>();


    // -------------------------------------------------------------------------
    // Construction
    // -------------------------------------------------------------------------

    private ApiErrorResponse(int status) {
        this.status = status;

        HttpStatus httpStatus = HttpStatus.resolve(status);
        this.title = httpStatus != null ? httpStatus.getReasonPhrase() : "Error";
        this.code = httpStatus != null ? httpStatus.name() : "ERROR";
    }

    public static ApiErrorResponse forStatus(int status) {
        return new ApiErrorResponse(status);
    }


    // -------------------------------------------------------------------------
    // Fluent setters
    // -------------------------------------------------------------------------

    public ApiErrorResponse withTitle(String title) {
        this.title = title;
        return this;
    }

    public ApiErrorResponse withDetail(String detail) {
        this.detail = detail;
        return this;
    }

    public ApiErrorResponse withInstance(URI instance) {
        this.instance = instance;
        return this;
    }

    public ApiErrorResponse withCode(String code) {
        this.code = code;
        return this;
    }

    public ApiErrorResponse withTimestamp(Instant timestamp) {
        this.timestamp = timestamp;
        return this;
    }

    public ApiErrorResponse withProperty(String key, Object value) {
        this.properties.put(key, value);
        return this;
    }


    // -------------------------------------------------------------------------
    // Serialization
    // -------------------------------------------------------------------------

    /// Exposes the additional members so they are written at the top level of the JSON object.
    @JsonAnyGetter
    public Map<String, Object> getProperties() {
        return properties;
    }
}
