package com.openshelves.model.enums;

public enum AuthorRole {
    AUTHOR,         // Primary writer of the work
    CO_AUTHOR,      // Joint primary writer of the work
    EDITOR,         // Responsible for editing and curating the content
    TRANSLATOR,     // Translated the work into another language
    ILLUSTRATOR,    // Created illustrations or artwork for the work
    PHOTOGRAPHER,   // Provided photographs for the work
    FOREWORD,       // Wrote the foreword
    INTRODUCTION,   // Wrote the introduction
    PREFACE,        // Wrote the preface
    AFTERWORD,      // Wrote the afterword
    CONTRIBUTOR,    // Made a general contribution to the work
    COMPILER,       // Compiled or assembled the work
    NARRATOR,       // Narrated the audiobook version of the work
}
